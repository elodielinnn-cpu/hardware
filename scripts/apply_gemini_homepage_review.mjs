import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { applyGeminiDecisions } from '../experiments/gemini-homepage-review/decision.mjs';

const dataPath = path.resolve(process.env.NEWS_DATA_PATH || 'real-data.js');
const sitePath = path.resolve(process.env.SITE_NEWS_DATA_PATH || 'site/real-data.js');
const storePath = path.resolve(process.env.GEMINI_REVIEW_STORE_PATH || 'outputs/gemini-homepage-review/latest.json');
const reportPath = path.resolve(process.env.GEMINI_RUN_REPORT_PATH || 'outputs/gemini-homepage-review/run-result.json');
const [store, report] = await Promise.all([
  fs.readFile(storePath, 'utf8').then(JSON.parse),
  fs.readFile(reportPath, 'utf8').then(JSON.parse)
]);
const input = await fs.readFile(dataPath, 'utf8');
const payload = new vm.Script(`${input}\n({ metadata: radarGenerationMetadata, articles: radarGeneratedArticles })`).runInNewContext(Object.create(null));
if (payload.metadata?.filterMode !== 'v3' || payload.metadata.articleCount !== payload.articles.length) {
  throw new Error('Refusing to apply review to an invalid or non-V3 news snapshot');
}
if (report.manifestStatus !== 'ready' || report.sourceGeneration?.generatedAt !== payload.metadata.generatedAt
  || report.sourceGeneration?.codeVersion !== payload.metadata.codeVersion
  || !Number.isInteger(report.summary?.selected) || !Number.isInteger(report.summary?.completed)
  || report.summary.providerStopped
  || (report.summary.selected > 0 && report.summary.completed === 0)) {
  throw new Error('Cloud review did not complete for this generated news snapshot; preserving published homepage');
}
const applied = applyGeminiDecisions(payload.articles, store);
if (applied.diagnostics.invalidStore || applied.diagnostics.invalid > 0) {
  throw new Error('Cloud review contains invalid decisions; preserving published homepage');
}
payload.metadata.homepageReviewMode = 'required';
payload.metadata.homepageReviewedAt = report.reviewedAt;
payload.metadata.homepageReviewedCount = applied.diagnostics.matched;
const output = `// Generated by scripts/fetch_real_sources.mjs; cloud review applied by scripts/apply_gemini_homepage_review.mjs\nconst radarGenerationMetadata = ${JSON.stringify(payload.metadata, null, 2)};\nconst radarGeneratedArticles = ${JSON.stringify(applied.articles, null, 2)};\n`;
await fs.writeFile(dataPath, output);
await fs.writeFile(sitePath, output);
const funnelPath = path.resolve(process.env.NEWS_SOURCE_FUNNEL_PATH || 'outputs/news-source-funnel/latest.json');
try {
  const funnel = JSON.parse(await fs.readFile(funnelPath, 'utf8'));
  if (funnel.generatedAt === payload.metadata.generatedAt && Array.isArray(funnel.sourceMetrics)) {
    const homepageArticles = new Map();
    for (const article of applied.articles) {
      if (article.showByDefault !== true) continue;
      if (!homepageArticles.has(article.sourceId)) homepageArticles.set(article.sourceId, []);
      homepageArticles.get(article.sourceId).push({
        title: article.title, url: article.sourceUrl, publishedAt: article.publishedAt
      });
    }
    for (const metric of funnel.sourceMetrics) {
      metric.reviewedHomepage = metric.status === 'configured_not_executed'
        ? null : (homepageArticles.get(metric.sourceId)?.length || 0);
      metric.homepageExamples = homepageArticles.get(metric.sourceId) || [];
    }
    funnel.reviewedAt = report.reviewedAt;
    await fs.writeFile(funnelPath, `${JSON.stringify(funnel, null, 2)}\n`);
  }
} catch (error) {
  if (error?.code !== 'ENOENT') console.warn(`Source funnel review counts unavailable: ${error.message}`);
}
console.log(JSON.stringify(applied.diagnostics));
